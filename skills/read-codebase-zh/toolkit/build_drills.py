"""Build a drills project: hub page, knowledge pages, one hint page per drill, and a PDF book.

    python3 build_drills.py path/to/drills.json [--pdf] [--shots] [--links] [--strict]

Project layout (everything relative to drills.json):

    drills.json
    src/index.md                  hub intro: how to use, setup, order        (optional)
    src/knowledge/<name>.md       domain knowledge pages, listed in "knowledge"
    src/hints/<stem>.md           one explanation + hints page per drill
    mine/<stem>.py                skeletons (generated by gen_stubs.py)
    tests/test_<stem>.py          acceptance tests
    solutions/<stem>.py           reference solutions, heavily commented
    ->  index.html  knowledge/<name>.html  hints/<stem>.html  <pdf>

drills.json:
    {
      "title": "Paged KV-cache drills", "lede": "...", "lang": "en", "slug": "paged-kv",
      "repo_url": "https://github.com/me/paged-kv-drills",              // optional
      "pins": {"vllm": {"repo": "vllm-project/vllm", "sha": "...", "local": "~/development/vllm"}},
      "tracks": [{"id": "A", "title": "Track A · Memory", "desc": "..."}],
      "drills": [{"id": "A1", "stem": "a1_block_pool", "title": "...", "minutes": 45,
                  "difficulty": "medium", "track": "A", "given": ["Block"]}],
      "knowledge": ["overview", "paged-attention"],
      "pdf": "paged-kv-drills.pdf",
      "quality": {"flows": 1, "steps": 1, "analogies": 1, "hints": 3}    // per hint page minimums
    }

Every drill must have mine/, tests/, solutions/ files and a hint page; every hint page must embed
the solution with {{code: solutions/<stem>.py}}. --strict turns quality misses into errors.
"""
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from mdx import I18N, Renderer, heading_ids, read_page  # noqa: E402
from page import outline_from_toc, render_page  # noqa: E402
from pins import Pins  # noqa: E402

UI = {
    "zh": {"home": "首页", "knowledge": "领域知识", "drills": "练习", "files": "文件", "mine": "你的代码", "test": "测试",
           "solution": "参考解", "hint": "讲解与提示", "done": "我已完成这道题", "progress": "{n} / {N} 题 · {m} / {M} 分钟",
           "minutes": "分钟", "prev": "← 上一题", "next": "下一题 →", "book": "PDF 手册", "kicker": "练习"},
    "en": {"home": "Home", "knowledge": "Knowledge", "drills": "Drills", "files": "Files", "mine": "your code", "test": "tests",
           "solution": "solution", "hint": "explainer & hints", "done": "I finished this drill",
           "progress": "{n} / {N} drills · {m} / {M} min", "minutes": "min", "prev": "← Previous", "next": "Next →",
           "book": "PDF book", "kicker": "Drill"},
}
DEFAULT_Q = {"flows": 1, "steps": 1, "analogies": 1, "hints": 3}


class Project:
    def __init__(self, cfg_path: Path):
        self.cfg_path = Path(cfg_path).resolve()
        self.root = self.cfg_path.parent
        self.cfg = json.loads(self.cfg_path.read_text(encoding="utf-8"))
        self.lang = self.cfg.get("lang", "en") if self.cfg.get("lang") in I18N else "en"
        self.ui = UI[self.lang]
        self.t = I18N[self.lang]
        self.pins = Pins(self.cfg.get("pins", {}), self.root)
        self.drills = self.cfg["drills"]
        self.tracks = {t["id"]: t for t in self.cfg.get("tracks", [])}
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.slug = self.cfg.get("slug") or re.sub(r"\W+", "-", self.cfg["title"].lower())[:40]

    def renderer(self, prefix):
        return Renderer(self.lang, self.pins, self.root, here_prefix=prefix)

    # ---------- navigation ----------
    def nav(self, prefix: str, current: str = "") -> str:
        u = self.ui
        out = [f'<a class="brand" href="{prefix}index.html">{html.escape(self.cfg.get("brand", self.cfg["title"]))}</a>']
        if self.cfg.get("knowledge"):
            out.append(f'<div class="nav-group">{u["knowledge"]}</div>')
            for name in self.cfg["knowledge"]:
                _, title, _ = read_page(self.root / "src" / "knowledge" / f"{name}.md")
                cls = " cur" if current == f"k:{name}" else ""
                out.append(f'<a class="nav-l3{cls}" href="{prefix}knowledge/{name}.html">{html.escape(title or name)}</a>')
        cur_track = None
        for d in self.drills:
            if d.get("track") != cur_track:
                cur_track = d.get("track")
                tt = self.tracks.get(cur_track, {}).get("title", cur_track or u["drills"])
                out.append(f'<div class="nav-group">{html.escape(tt)}</div>')
            cls = " cur" if current == d["id"] else ""
            out.append(f'<a class="nav-l3{cls}" data-id="{d["id"]}" href="{prefix}hints/{d["stem"]}.html">'
                       f'<span class="nid">{d["id"]}</span>{html.escape(d["title"])}</a>')
        return "\n".join(out)

    def page(self, *, title, body, prefix, current="", toc=None, cover="", footer=""):
        return render_page(title=title, body=body, lang=self.lang, nav=self.nav(prefix, current),
                           outline=outline_from_toc(toc or [], self.t["outline"]), cover=cover, footer=footer,
                           store_key=self.slug, copied=self.t["copied"], theme_label=self.t["theme"])

    # ---------- pages ----------
    def drill_files(self, d, prefix):
        u = self.ui
        base = self.cfg.get("repo_url")
        links = []
        for label, path in ((u["mine"], f"mine/{d['stem']}.py"), (u["test"], f"tests/test_{d['stem']}.py"),
                            (u["solution"], f"solutions/{d['stem']}.py")):
            if not (self.root / path).exists():
                self.errors.append(f"{d['id']}: missing {path}")
            href = f"{base}/blob/main/{path}" if base else prefix + path
            links.append(f'<a href="{href}"><code>{path}</code></a> <span class="muted small">{label}</span>')
        return " · ".join(links)

    def hint_page(self, k):
        d, u = self.drills[k], self.ui
        src = self.root / "src" / "hints" / f"{d['stem']}.md"
        if not src.exists():
            self.errors.append(f"{d['id']}: missing src/hints/{d['stem']}.md")
            return "", []
        lede, title, lines = read_page(src)
        r = self.renderer("../")
        body, toc = heading_ids(r.render(lines), f"{d['id'].lower()}-")
        self.errors += [f"{d['id']}: {e}" for e in r.errors]
        text = src.read_text(encoding="utf-8")
        if f"solutions/{d['stem']}.py" not in text:
            self.errors.append(f"{d['id']}: hint page does not embed {{{{code: solutions/{d['stem']}.py}}}}")
        q = {**DEFAULT_Q, **self.cfg.get("quality", {})}
        got = {"flows": r.stats["flows"], "steps": r.stats["steps"], "analogies": r.stats["analogies"],
               "hints": r.stats["hints"]}
        for key, need in q.items():
            if got.get(key, 0) < need:
                self.warnings.append(f"{d['id']}: {key} = {got.get(key, 0)} < {need}")
        track = self.tracks.get(d.get("track"), {}).get("title", "")
        meta = f'{d["id"]} · {track} · {d.get("minutes", "?")} {u["minutes"]} · {d.get("difficulty", "")}'
        cover = (f'<header class="cover"><div class="kicker">{html.escape(meta)}</div>'
                 f'<h1>{html.escape(title or d["title"])}</h1>'
                 + (f'<p class="lede">{r.md_inline(lede)}</p>' if lede else "")
                 + f'<p class="small">{u["files"]}: {self.drill_files(d, "../")}</p>'
                 f'<label class="done-row"><input type="checkbox" id="done-box" data-id="{d["id"]}"> {u["done"]}</label>'
                 "</header>")
        prev_d = self.drills[k - 1] if k > 0 else None
        next_d = self.drills[k + 1] if k + 1 < len(self.drills) else None
        pager = '<nav class="pager">' + (
            f'<a href="{prev_d["stem"]}.html">{u["prev"]} {prev_d["id"]}</a>' if prev_d else "<span></span>") + (
            f'<a href="{next_d["stem"]}.html">{next_d["id"]} {u["next"]}</a>' if next_d else "<span></span>") + "</nav>"
        html_page = self.page(title=f'{d["id"]} · {d["title"]}', body=body, prefix="../", current=d["id"],
                              toc=toc, cover=cover, footer=pager)
        return html_page, (cover, body)

    def knowledge_page(self, name):
        src = self.root / "src" / "knowledge" / f"{name}.md"
        if not src.exists():
            self.errors.append(f"knowledge: missing src/knowledge/{name}.md")
            return "", ("", "")
        lede, title, lines = read_page(src)
        r = self.renderer("../")
        body, toc = heading_ids(r.render(lines), f"k-{name}-")
        self.errors += [f"knowledge/{name}: {e}" for e in r.errors]
        cover = (f'<header class="cover"><div class="kicker">{self.ui["knowledge"]}</div>'
                 f'<h1>{html.escape(title or name)}</h1>'
                 + (f'<p class="lede">{r.md_inline(lede)}</p>' if lede else "") + "</header>")
        return self.page(title=title or name, body=body, prefix="../", current=f"k:{name}", toc=toc, cover=cover), \
            (cover, body)

    def index_page(self):
        u = self.ui
        r = self.renderer("")
        intro = ""
        if (self.root / "src" / "index.md").exists():
            _, _, lines = read_page(self.root / "src" / "index.md")
            intro = r.render(lines)
            self.errors += [f"index: {e}" for e in r.errors]
        parts = [intro]
        if self.cfg.get("knowledge"):
            cards = []
            for name in self.cfg["knowledge"]:
                lede, title, _ = read_page(self.root / "src" / "knowledge" / f"{name}.md")
                cards.append(f'<a class="card" href="knowledge/{name}.html"><div class="ctitle">{html.escape(title or name)}</div>'
                             f'<div class="cmeta">{r.md_inline(lede)}</div></a>')
            parts.append(f'<h2>{u["knowledge"]}</h2><div class="cards">{"".join(cards)}</div>')
        total = sum(d.get("minutes", 0) for d in self.drills)
        parts.append(f'<h2>{u["drills"]}</h2><div class="progress"><div id="prog-bar"></div></div>'
                     f'<div class="small muted" id="prog-text" data-fmt="{html.escape(u["progress"])}"></div>')
        cur_track, cards = None, []

        def flush_track():
            if cards:
                parts.append(f'<div class="cards">{"".join(cards)}</div>')
                cards.clear()

        for d in self.drills:
            if d.get("track") != cur_track:
                flush_track()
                cur_track = d.get("track")
                tr = self.tracks.get(cur_track, {})
                parts.append(f'<h3>{html.escape(tr.get("title", cur_track or ""))}</h3>'
                             + (f'<p class="muted small">{r.md_inline(tr.get("desc", ""))}</p>' if tr.get("desc") else ""))
            cards.append(
                f'<div class="card" data-id="{d["id"]}" data-min="{d.get("minutes", 0)}">'
                f'<div><input type="checkbox" class="chk" aria-label="done"> <span class="cid">{d["id"]}</span> '
                f'<span class="cmeta">{d.get("minutes", "?")} {u["minutes"]} · {html.escape(str(d.get("difficulty", "")))}</span></div>'
                f'<div class="ctitle"><a href="hints/{d["stem"]}.html">{html.escape(d["title"])}</a></div>'
                f'<div class="clinks"><a href="hints/{d["stem"]}.html">{u["hint"]}</a>'
                f'<a href="mine/{d["stem"]}.py">mine/</a><a href="tests/test_{d["stem"]}.py">tests/</a>'
                f'<a href="solutions/{d["stem"]}.py">solutions/</a></div></div>')
        flush_track()
        if self.cfg.get("pdf"):
            parts.append(f'<p><a href="{self.cfg["pdf"]}">📄 {u["book"]}: {self.cfg["pdf"]}</a></p>')
        body, toc = heading_ids("\n".join(parts), "h-")
        cover = (f'<header class="cover"><div class="kicker">{html.escape(self.cfg.get("kicker", u["drills"]))} · '
                 f'{len(self.drills)} × · {total} {u["minutes"]}</div><h1>{html.escape(self.cfg["title"])}</h1>'
                 + (f'<p class="lede">{r.md_inline(self.cfg["lede"])}</p>' if self.cfg.get("lede") else "") + "</header>")
        return self.page(title=self.cfg["title"], body=body, prefix="", toc=toc, cover=cover), (cover, body)

    # ---------- build ----------
    def build(self, *, pdf=False, shots=False, links=False, strict=False) -> int:
        (self.root / "hints").mkdir(exist_ok=True)
        (self.root / "knowledge").mkdir(exist_ok=True)
        book = []
        idx, part = self.index_page()
        (self.root / "index.html").write_text(idx, encoding="utf-8")
        book.append(part)
        for name in self.cfg.get("knowledge", []):
            pg, part = self.knowledge_page(name)
            if pg:
                (self.root / "knowledge" / f"{name}.html").write_text(pg, encoding="utf-8")
                book.append(part)
        for k, d in enumerate(self.drills):
            pg, part = self.hint_page(k)
            if pg:
                (self.root / "hints" / f"{d['stem']}.html").write_text(pg, encoding="utf-8")
                book.append(part)
        self.errors += self.pins.errors
        n_flows = sum(p[1].count('class="flow"') for p in book)
        print(f"built index.html + {len(self.cfg.get('knowledge', []))} knowledge pages + {len(self.drills)} hint pages · "
              f"{n_flows} diagrams · {self.pins.count} source links")
        for w in self.warnings:
            print(("ERROR " if strict else "warn  ") + w)
        for e in self.errors:
            print("ERROR " + e)
        if self.errors or (strict and self.warnings):
            return 1
        pages = [self.root / "index.html"] + sorted((self.root / "knowledge").glob("*.html")) + \
            sorted((self.root / "hints").glob("*.html"))
        if shots:
            from shots import shots as do_shots
            n = 0
            for p in pages[1:]:
                n += len(do_shots(p, self.root / ".shots" / p.stem))
            print(f"diagram screenshots in {self.root / '.shots'} — open and look at every one")
        if links:
            from check_links import main as check
            if check(pages):
                return 1
        if pdf and self.cfg.get("pdf"):
            # one print-only page: every section starts on a new page, relative links fixed for the root
            sections = []
            for i, (cover, body) in enumerate(book):
                b = body.replace('href="../', 'href="')
                sections.append(f'<section class="{"page-break" if i else ""}">{cover}{b}</section>')
            tmp = self.root / ".book.html"
            tmp.write_text(render_page(title=self.cfg["title"], body="\n".join(sections), lang=self.lang,
                                       store_key=self.slug), encoding="utf-8")
            from make_pdf import make_pdf, page_count
            out = make_pdf(tmp, self.root / self.cfg["pdf"])
            tmp.unlink(missing_ok=True)
            print(f"wrote {out.name} · {page_count(out)} pages · {out.stat().st_size // 1024} KB")
        return 0


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        raise SystemExit(__doc__)
    flags = {a for a in sys.argv[1:] if a.startswith("--")}
    sys.exit(Project(Path(args[0])).build(pdf="--pdf" in flags, shots="--shots" in flags, links="--links" in flags,
                                          strict="--strict" in flags))
